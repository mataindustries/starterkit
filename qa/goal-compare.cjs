#!/usr/bin/env node
/* Side-by-side comparison of the three marketing goals for one fictional business, made with the
   page's own copy and drawing code, so it always shows exactly what the app gives an owner.
   Nothing leaves this machine.

     node qa/goal-compare.cjs      → qa/goals/COMPARISON.md, qa/goals/plans-en.png, qa/goals/plans-es.png

   The business is fictional; 555-01xx is a reserved fictional phone range. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(__dirname, 'goals');
const BIZ = { name: 'Bright Path Cleaning', service: 'cleaning', area: 'Glendora', phone: '6265550142', handle: 'brightpathclean' };
const GOALS = ['', 'sell', 'proof', 'brand'];

/* Runs in the page: every plan, suggestion and a post thumbnail per goal (Editorial and Luxury). */
async function collect(biz) {
  const A = window.ENMStarter; await A.fontsReady;
  const kind = i => { const s = (i.w + ' ' + i.h).toLowerCase();
    return /carousel|carrusel/.test(s) ? 'carousel' : /\bstory\b|historia/.test(s) ? 'Story' : /slides|dos imágenes/.test(s) ? 'two slides' : /video|clip|film|gr[aá]b|camera|cámara/.test(s) ? 'video' : /graphic|gráficos/.test(s) ? 'app graphic' : /screenshot|captura/.test(s) ? 'screenshot' : 'photo'; };
  const thumb = (d, t) => { const c = document.createElement('canvas'); c.width = 1080; c.height = 1350; A.render(c.getContext('2d'), 1080, 1350, d, t);
    const s = document.createElement('canvas'); s.width = 432; s.height = 540; const x = s.getContext('2d'); x.imageSmoothingQuality = 'high'; x.drawImage(c, 0, 0, 432, 540); return s.toDataURL('image/png'); };
  const out = {};
  for (const lang of ['en', 'es']) for (const goal of ['', 'sell', 'proof', 'brand']) {
    const d = A.deriveData(Object.assign({}, A.DEF, biz, { lang, goal }), null), C = A.buildCopy(d), G = goal ? A.GOALS[goal][lang] : null;
    out[`${lang}/${goal}`] = { name: G ? G.name : (lang === 'es' ? 'Plan general (sin meta)' : 'General plan (no goal)'), hint: G ? G.hint : '', intro: G ? G.intro : A.UI[lang].weekIntro,
      hls: d.hls, ctas: d.ctas, bio: C.bio, ideas: C.ideas.map(i => Object.assign({ kind: kind(i) }, i)), post: thumb(d, 0), lux: thumb(d, 3) };
  }
  return out;
}

const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function markdown(P) {
  const L = [];
  const g3 = GOALS.slice(1);
  L.push('# Marketing goals · three Week 1 plans for the same business', '',
    `One fictional business, **${BIZ.name}** (house cleaning, ${BIZ.area}, (626) 555-0142), with nothing else changed but the goal.`,
    'Generated by `node qa/goal-compare.cjs` from `index.html` with the app\'s own copy code, so this is word for word what an owner sees.',
    'Anything in [brackets] is a blank the owner fills in with real details before posting.', '',
    '![Three plans side by side](plans-en.png)', '',
    '## The week at a glance', '',
    '| Day | General plan (no goal, unchanged) | Sell now | Show proof | Build brand |', '|---|---|---|---|---|');
  for (let i = 0; i < 7; i++) L.push(`| ${i + 1} | ${GOALS.map(g => { const x = P[`en/${g}`].ideas[i]; return `${cell(x.t)} · *${x.kind}*`; }).join(' | ')} |`);
  L.push('', '| Día | Plan general (sin meta) | Conseguir clientes | Mostrar mi trabajo | Darme a conocer |', '|---|---|---|---|---|');
  for (let i = 0; i < 7; i++) L.push(`| ${i + 1} | ${GOALS.map(g => cell(P[`es/${g}`].ideas[i].t)).join(' | ')} |`);
  L.push('', '## Graphics suggestions', '',
    'The first idea is what the Graphics tab shows when the goal is picked; **Another idea** cycles through the rest. A headline or call to action the owner typed is never replaced.', '',
    '| Goal | Headline ideas | Call-to-action ideas |', '|---|---|---|');
  for (const g of GOALS) for (const lang of ['en', 'es']) { const p = P[`${lang}/${g}`]; L.push(`| ${cell(p.name)} | ${p.hls.map(cell).join('<br>')} | ${p.ctas.map(cell).join('<br>')} |`); }
  L.push('', 'The bio, the About text and the five customer messages are the same for every goal (the bio keeps the general call to action).', '');
  for (const g of g3) {
    const en = P[`en/${g}`], es = P[`es/${g}`];
    L.push(`## ${en.name} · ${es.name}`, '', `*${en.intro}*`, '');
    en.ideas.forEach((x, i) => L.push(`**Day ${i + 1} · ${x.t}** (${x.kind})`, '', `- **Post:** ${x.w}`, `- **How:** ${x.h}`, `- **Caption starter:** ${x.c}`, ''));
    L.push('<details><summary>En español</summary>', '', `*${es.intro}*`, '');
    es.ideas.forEach((x, i) => L.push(`**Día ${i + 1} · ${x.t}**`, '', `- **Qué publicar:** ${x.w}`, `- **Cómo:** ${x.h}`, `- **Texto para empezar:** ${x.c}`, ''));
    L.push('</details>', '');
  }
  L.push('## Phone-width screenshots', '', 'Taken by `node qa/run-checks.cjs` in Chromium at real Android widths (2× pixel density).', '',
    '| 320 px | 360 px | 412 px |', '|---|---|---|',
    '| ![320 EN](selector-320-en.png) | ![360 EN](selector-360-en.png) | ![412 EN](selector-412-en.png) |',
    '| ![320 ES](selector-320-es.png) | ![360 ES](selector-360-es.png) | ![412 ES](selector-412-es.png) |', '',
    'Week 1 after picking a goal, at 360 px:', '', '| English · Sell now | Español · Conseguir clientes |', '|---|---|', '| ![Week 1 EN](week1-360-en.png) | ![Semana 1 ES](week1-360-es.png) |', '');
  return L.join('\n');
}

function sheetHtml(P, lang) {
  const es = lang === 'es';
  const col = g => { const p = P[`${lang}/${g}`];
    return `<section><h2>${esc(p.name)}</h2><p class="hint">${esc(p.hint)}</p>
      <div class="thumbs"><img src="${p.post}" alt=""><img src="${p.lux}" alt=""></div>
      <p class="sug"><b>${es ? 'Título' : 'Headline'}:</b> ${esc(p.hls[0])}<br><b>${es ? 'Llamado' : 'CTA'}:</b> ${esc(p.ctas[0])}</p>
      <ol>${p.ideas.map((x, i) => `<li><div class="day">${es ? 'Día' : 'Day'} ${i + 1} · <span>${esc(x.kind)}</span></div><h3>${esc(x.t)}</h3><p>${esc(x.c).replace(/\[[^\]]+\]/g, m => `<mark>${m}</mark>`)}</p></li>`).join('')}</ol></section>`; };
  return `<!doctype html><meta charset="utf-8"><style>
    body{margin:0;padding:36px 44px 30px;background:#ECE8E1;font:15px/1.45 Inter,system-ui,Roboto,Arial,sans-serif;color:#1C1813;width:1452px}
    h1{font:600 30px/1.15 Lora,Georgia,serif;margin:0 0 6px} .lede{margin:0 0 26px;color:#5c554d;max-width:1200px}
    .cols{display:grid;grid-template-columns:repeat(3,1fr);gap:28px} section{background:#FBF8F3;border:1px solid rgba(23,21,18,.12);border-radius:18px;padding:22px 22px 8px}
    h2{font:600 24px/1.2 Lora,Georgia,serif;margin:0 0 4px} .hint{margin:0 0 14px;color:#857C71;font-size:14px}
    .thumbs{display:flex;gap:10px;margin:0 0 12px} .thumbs img{width:calc(50% - 5px);border-radius:6px;box-shadow:0 6px 16px -10px rgba(0,0,0,.5)}
    .sug{font-size:13.5px;margin:0 0 12px;color:#4A443D} ol{list-style:none;margin:0;padding:0} li{border-top:1px solid rgba(23,21,18,.1);padding:10px 0 9px}
    .day{font:600 11px/1 Inter,sans-serif;letter-spacing:.12em;text-transform:uppercase;color:#E2542B;margin:0 0 5px} .day span{color:#857C71;letter-spacing:.06em}
    h3{font:600 16px/1.25 Lora,Georgia,serif;margin:0 0 4px} li p{margin:0;font-size:13.5px;color:#4A443D}
    mark{background:rgba(226,84,43,.14);color:inherit;border-radius:3px;padding:0 2px} .foot{margin:18px 0 0;color:#857C71;font-size:13px}
  </style><h1>${es ? 'Tres metas, tres semanas distintas · mismo negocio' : 'Three goals, three different weeks · same business'}</h1>
  <p class="lede">${es ? `${BIZ.name} (limpieza de casas, ${BIZ.area}). Solo cambia la meta. Para cada una: la publicación con el título y el llamado sugeridos (estilos Editorial y Lujo) y los 7 días con su formato y el texto para empezar.`
    : `${BIZ.name} (house cleaning, ${BIZ.area}). Only the goal changes. For each: the post with its suggested headline and call to action (Editorial and Luxury styles), then the 7 days with their format and caption starter.`}</p>
  <div class="cols">${GOALS.slice(1).map(col).join('')}</div>
  <p class="foot">${es ? 'Generado por qa/goal-compare.cjs con el propio código de la app. Negocio ficticio; lo que está entre [corchetes] lo llena el dueño con datos reales.' : 'Rendered by qa/goal-compare.cjs with the app’s own code. Fictional business; [brackets] are blanks the owner fills in with real details.'}</p>`;
}

(async () => {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(html); });
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
  try {
    fs.mkdirSync(OUT, { recursive: true });
    const page = await browser.newPage();
    await page.addInitScript(() => { window.__ENM_NO_APP = true; });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const P = await page.evaluate(collect, BIZ);
    fs.writeFileSync(path.join(OUT, 'COMPARISON.md'), markdown(P));
    console.log('wrote qa/goals/COMPARISON.md');
    // The sheet uses the app's own embedded fonts (its @font-face rules, data URLs only).
    const faces = html.split('\n').filter(l => /^@font-face/.test(l)).join('\n');
    for (const lang of ['en', 'es']) {
      const sheet = await browser.newPage({ viewport: { width: 1540, height: 900 }, deviceScaleFactor: 1 });
      await sheet.setContent(sheetHtml(P, lang).replace('<style>', `<style>${faces}\n`));
      await sheet.evaluate(async () => { await Promise.all(['400 15px Inter', '600 15px Inter', '600 24px Lora'].map(f => document.fonts.load(f))); await document.fonts.ready; });
      await sheet.screenshot({ path: path.join(OUT, `plans-${lang}.png`), fullPage: true });
      await sheet.close();
      console.log(`wrote qa/goals/plans-${lang}.png`);
    }
  } finally { await browser.close(); server.close(); }
})().catch(e => { console.error(e); process.exit(1); });
